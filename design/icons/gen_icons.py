"""Generates android/.../ui/Lucide.kt from lucide icons (ISC license), the icon set of replai-admin.

Usage: python design/icons/gen_icons.py <lucide-react>/dist/esm/icons > android/app/src/main/java/kg/crosslink/app/ui/Lucide.kt
Android vectors only draw paths, so circles, rects, lines and polylines are converted to path data.
Path data is re-tokenized because lucide packs arc flags ("a2 2 0 011 1") in a way some parsers misread.
"""
import re
import sys
from pathlib import Path

ICONS = {
    "Send": "send", "Copy": "copy", "Clipboard": "clipboard", "Image": "image", "File": "file",
    "ArrowUpRight": "arrow-up-right", "ArrowDownLeft": "arrow-down-left", "ExternalLink": "external-link",
    "X": "x", "Check": "check", "Laptop": "laptop", "ScanQrCode": "scan-qr-code", "Lock": "lock",
    "Power": "power", "RotateCw": "rotate-cw", "Trash": "trash-2", "Link": "link", "CircleAlert": "circle-alert",
    "WifiOff": "wifi-off", "Keyboard": "keyboard",
}
ARGS = {"m": 2, "l": 2, "h": 1, "v": 1, "c": 6, "s": 4, "q": 4, "t": 2, "a": 7, "z": 0}
NUMBER = re.compile(r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")


def fmt(value: float) -> str:
    text = f"{value:.3f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def normalize(d: str) -> str:
    out, i = [], 0
    command = None
    while i < len(d):
        ch = d[i]
        if ch in " ,\t\n":
            i += 1
            continue
        if ch.isalpha():
            command = ch
            out.append(ch)
            i += 1
            if ch.lower() == "z":
                command = None
            continue
        if out and out[-1] != command:
            out.append(command)  # spell out implicit repeats ("M7 17 17 7" -> "M 7 17 L 17 7")
        count = ARGS[command.lower()]
        params = []
        for index in range(count):
            while d[i] in " ,":
                i += 1
            if command.lower() == "a" and index in (3, 4):
                params.append(d[i])
                i += 1
            else:
                match = NUMBER.match(d, i)
                params.append(fmt(float(match.group())))
                i = match.end()
        out.append(" ".join(params))
        if command == "m":
            command = "l"
        elif command == "M":
            command = "L"
    return " ".join(out)


def rounded_rect(x, y, w, h, rx, ry):
    if not rx and not ry:
        return f"M{fmt(x)} {fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}z"
    rx, ry = rx or ry, ry or rx
    return (f"M{fmt(x + rx)} {fmt(y)}h{fmt(w - 2 * rx)}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(ry)}"
            f"v{fmt(h - 2 * ry)}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(ry)}h{fmt(-(w - 2 * rx))}"
            f"a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(-rx)} {fmt(-ry)}v{fmt(-(h - 2 * ry))}a{fmt(rx)} {fmt(ry)} 0 0 1 {fmt(rx)} {fmt(-ry)}z")


def to_path(tag: str, a: dict) -> str:
    f = lambda key, default=0.0: float(a.get(key, default))
    if tag == "path":
        return a["d"]
    if tag in ("circle", "ellipse"):
        rx = f("r") if tag == "circle" else f("rx")
        ry = f("r") if tag == "circle" else f("ry")
        cx, cy = f("cx"), f("cy")
        return (f"M{fmt(cx - rx)} {fmt(cy)}a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(2 * rx)} 0"
                f"a{fmt(rx)} {fmt(ry)} 0 1 0 {fmt(-2 * rx)} 0z")
    if tag == "rect":
        return rounded_rect(f("x"), f("y"), f("width"), f("height"), f("rx"), f("ry"))
    if tag == "line":
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if tag in ("polyline", "polygon"):
        points = NUMBER.findall(a["points"])
        pairs = [f"{points[k]} {points[k + 1]}" for k in range(0, len(points), 2)]
        return "M" + "L".join(pairs) + ("z" if tag == "polygon" else "")
    raise ValueError(tag)


def icon_paths(source: str) -> list[str]:
    node = source.split("const __iconNode = [", 1)[1].split("];", 1)[0]
    paths = []
    for tag, attrs in re.findall(r'\[\s*"(\w+)",\s*\{([^}]*)\}\s*\]', node):
        values = dict(re.findall(r'(\w+):\s*"([^"]*)"', attrs))
        paths.append(normalize(to_path(tag, values)))
    return paths


def main(folder: str) -> None:
    lines = [
        "package kg.crosslink.app.ui",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.StrokeCap",
        "import androidx.compose.ui.graphics.StrokeJoin",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.addPathNodes",
        "import androidx.compose.ui.unit.dp",
        "",
        "// Generated by design/icons/gen_icons.py from lucide (ISC), the icon set of replai-admin. Do not edit.",
        "object Lucide {",
    ]
    for name, file in ICONS.items():
        paths = icon_paths(Path(folder, f"{file}.mjs").read_text())
        args = ", ".join(f'"{p}"' for p in paths)
        lines.append(f'    val {name}: ImageVector by lazy {{ icon("{name}", {args}) }}')
    lines += [
        "}",
        "",
        "/** 24-unit lucide outline: stroke 2, round caps and joins; Icon() tints it with the content color. */",
        "private fun icon(name: String, vararg paths: String): ImageVector =",
        "    ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f).apply {",
        "        paths.forEach {",
        "            addPath(addPathNodes(it), fill = null, stroke = SolidColor(Color.Black), strokeLineWidth = 2f,",
        "                strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round)",
        "        }",
        "    }.build()",
        "",
    ]
    sys.stdout.write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
